// 階層ごとの敵の出現テーブル（揺らぎ）。夜の深さで種類と数が増える
// S 錆兵 / A 時計弓兵 / R 歯車転がし / L 鐘撞き / B 振り子蝙蝠 / P 刻の亡霊 / T 時計砲台
function floorEnemies(floor, nl) {
  // E 光線砲手 / N 鎖鎌兵 / F 歯車ネズミ / J 跳ね潰し / H 大槌兵
  const g = [['S', 'S', 'A', 'F', 'H'], ['S', 'R', 'A', 'L', 'N', 'J', 'H'], ['S', 'A', 'R', 'L', 'E', 'N', 'J', 'F', 'H']][floor].slice();
  if (nl >= 1 && floor === 0) g.push('J', 'N');
  if (nl >= 2 && floor <= 1) g.push('E');
  const a = [['B'], ['B', 'P'], ['B', 'P']][floor].slice();
  if (nl >= 1 && floor === 0) g.push('R');
  if (nl >= 2 && floor === 0) { g.push('L'); a.push('P'); }
  if (nl >= 1 && floor >= 1) a.push('P');
  const fill = Math.min(1, [0.7, 0.85, 1][floor] + 0.06 * nl);
  const min = [2, 3, 3][floor] + Math.floor(nl / 2);
  return { g, a, t: ['T'], fill, min };
}
// 脅威で増える敵の種類（弓兵と砲台は増やさない）
export function extraEnemyTypes(floor, nl) {
  const t = floorEnemies(floor, nl);
  return { g: t.g.filter((c) => c !== 'A' && c !== 'E'), a: t.a };
}
const COMBAT_POOLS = [
  ['alley', 'steps', 'pit', 'watch', 'hall', 'pillars', 'islands', 'cage', 'ruins', 'terrace'],
  ['gears', 'watch', 'hall', 'pit', 'steps', 'bridge', 'twin', 'tower', 'canyon', 'atrium', 'ruins'],
  ['gears', 'hall', 'alley', 'drop', 'tower', 'bridge', 'twin', 'canyon', 'islands', 'atrium', 'terrace'],
];

export const FLOOR_NAMES = ['下層・市場', '中層・歯車回廊', '上層・鐘楼'];

function fillEnemies(layoutName, floor, rng, nl) {
  const t = floorEnemies(floor, nl);
  const rows = LAYOUTS[layoutName];
  const slots = [];
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === 'g' || c === 'a' || c === 't') slots.push({ c, x, y }); }));
  const chosen = slots.filter(() => rng.next() < t.fill);
  // 最低数を保証
  for (const s of rng.shuffle(slots)) { if (chosen.length >= Math.min(t.min, slots.length)) break; if (!chosen.includes(s)) chosen.push(s); }
  return chosen.map((s) => ({ type: rng.pick(t[s.c]), x: s.x, y: s.y }));
}

// 扉の報酬：強化・回復・砂時計・金貨袋・アーティファクト
function rollReward(rng) {
  const r = rng.next();
  return r < 0.46 ? 'boon' : r < 0.64 ? 'heal' : r < 0.74 ? 'hourglass' : r < 0.88 ? 'gold' : 'artifact';
}

// 周回の塔の構成を作る。seed は揺らぎだけに使い、因果は meta から決める。
export function buildPlan(meta, seed) {
  const rng = makeRng(seed);
  const nl = Math.max(0, meta.loop - 1);
  const combat = (layout, floor, r) => {
    const enemies = fillEnemies(layout, floor, r, nl);
    // 半分の確率で左右反転（同じ形でも違う部屋に感じる）
    const mirror = r.next() < 0.5;
    const w = LAYOUTS[layout][0].length;
    if (mirror) for (const e of enemies) e.x = w - 1 - e.x;
    return { type: 'combat', layout, enemies, mirror };
  };
  // 試練の間：2 波の敵を退けると、アーティファクトと金貨
  const trial = (floor, r) => {
    const layout = r.pick(['hall', 'atrium']);
    const waves = [fillEnemies(layout, floor, r, nl + 1), fillEnemies(layout, floor, r, nl + 2)];
    return { type: 'trial', layout, waves, enemies: waves[0], mirror: false };
  };
  const floors = [];
  // 下層
  const p0 = rng.shuffle(COMBAT_POOLS[0]);
  floors.push([
    { type: 'entry', layout: 'entry' },
    combat(p0[0], 0, rng), combat(p0[1], 0, rng),
    { type: 'forge', layout: 'forge' },
    combat(p0[2], 0, rng),
    { type: 'shrine', layout: 'shrine' },
    { type: 'shop', layout: 'shop' },
  ]);
  // 中層
  const p1 = rng.shuffle(COMBAT_POOLS[1]);
  floors.push([
    combat(p1[0], 1, rng),
    { type: 'elite', layout: 'arena', knightWedged: hasWedge(meta, 'knight') },
    { type: 'archive', layout: 'archive' },
    combat(p1[1], 1, rng),
    trial(1, rng),
    { type: 'shop', layout: 'shop' },
  ]);
  // 上層
  const p2 = rng.shuffle(COMBAT_POOLS[2]);
  floors.push([
    combat(p2[0], 2, rng),
    { type: 'study', layout: 'study' },
    combat(p2[1], 2, rng),
    { type: 'elite2', layout: 'warden' },
    { type: 'boss', layout: 'belfry' },
  ]);
  // 各部屋の報酬（入る前に扉で見える）
  for (const f of floors) for (const r of f) {
    if (r.type === 'combat') r.rewardChoices = [rollReward(rng), rollReward(rng)];
    if (r.type === 'combat' && r.rewardChoices[0] !== 'boon' && r.rewardChoices[1] !== 'boon') r.rewardChoices[0] = 'boon';
  }
  return { seed, floors, offerSeed: rng.int(1, 1e9) };
}

// 部屋の行（反転を反映）
// 反転した部屋でも、出現位置は左・出口は右になるよう P と X を入れ替える
export function mirrorRows(rows) {
  const m = rows.map((r) => [...r].reverse().join(''));
  const find = (c) => { for (let y = 0; y < m.length; y++) { const x = m[y].indexOf(c); if (x >= 0) return { x, y }; } return null; };
  const P = find('P'), X = find('X');
  if (!P || !X || P.x < m[0].length / 2) return m;
  const set = (pos, c) => { m[pos.y] = m[pos.y].slice(0, pos.x) + c + m[pos.y].slice(pos.x + 1); };
  set(P, 'X'); set(X, 'P');
  return m;
}
export function layoutRows(desc) {
  const rows = LAYOUTS[desc.layout];
  return desc.mirror ? mirrorRows(rows) : rows;
}
